"""Export helpers: Markdown text and PDF via reportlab."""

from __future__ import annotations

import io
from typing import Any


def to_markdown(result: dict[str, Any], source: str, explanation_md: str,
                filename: str) -> str:
    s = result["summary"]
    parts = [
        f"# Code Explanation — {filename}",
        "",
        f"- **Language:** {s.get('language', 'unknown')} ({s.get('analysis_kind', '?')} analysis)",
        f"- **Lines:** {s['total_lines']} total, {s['non_blank_lines']} non-blank",
        f"- **Structure:** {s['functions']} functions, {s['classes']} classes, "
        f"{s['methods']} methods, {s['imports']} imports",
        "",
        "## Source code",
        "",
        "```" + (s.get("language", "").lower() if s.get("language") else "") + "\n" +
        (source[:20000] if len(source) <= 20000 else source[:20000] + "\n# … truncated for export") +
        "\n```",
        "",
        explanation_md,
        "",
        "---",
        "*Generated by Code Explanation Assistant — static analysis only.*",
    ]
    cov = result.get("coverage")
    if cov:
        parts.insert(6, f"- **Coverage:** {cov['percent']}% of lines analysed "
                         f"({cov['segments_analyzed']}/{cov['segments_total']} segments)")
    return "\n".join(parts)


def to_pdf(result: dict[str, Any], explanation_md: str, filename: str) -> bytes:
    """Render the explanation as a simple, readable PDF."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.pdfgen import canvas

    s = result["summary"]
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    width, height = A4
    margin = 18 * mm
    y = height - margin
    max_chars = 95

    def new_page() -> None:
        nonlocal y
        c.showPage()
        y = height - margin

    def line(text: str, size: int = 10, bold: bool = False, gap: float = 4) -> None:
        nonlocal y
        c.setFont("Helvetica-Bold" if bold else "Helvetica", size)
        # naive wrap
        words = text.split()
        current = ""
        for word in words:
            trial = f"{current} {word}".strip()
            if len(trial) > max_chars and current:
                if y < margin + 10:
                    new_page()
                c.drawString(margin, y, current)
                y -= size + 2
                current = word
            else:
                current = trial
        if current:
            if y < margin + 10:
                new_page()
            c.drawString(margin, y, current)
            y -= size + gap

    line(f"Code Explanation — {filename}", 16, True, 10)
    line(f"Language: {s.get('language', 'unknown')} | Lines: {s['total_lines']} | "
         f"Functions: {s['functions']} | Classes: {s['classes']}", 10)
    y -= 6

    # Feed the markdown through a light-weight renderer: headings bold,
    # bullets indented, code fences in courier.
    in_code = False
    for raw in explanation_md.splitlines():
        text = raw.rstrip()
        if text.startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            if y < margin + 10:
                new_page()
            c.setFont("Courier", 8)
            c.drawString(margin, y, text[:110])
            y -= 9
            continue
        if not text.strip():
            y -= 4
            continue
        if text.startswith("#"):
            level = len(text) - len(text.lstrip("#"))
            line(text.lstrip("# ").strip(), 13 if level <= 2 else 11, True, 6)
        elif text.startswith("- ") or text.startswith("  - "):
            indent = 8 if text.startswith("  ") else 0
            line("• " + text.lstrip("- ").strip(), 9, False, 3)
            # keep indent simple: drawString already at margin; acceptable
        elif text.startswith("**") and text.endswith("**"):
            line(text.strip("*"), 10, True, 3)
        else:
            clean = text.replace("**", "").replace("`", "")
            line(clean, 9, False, 3)
        if y < margin + 10:
            new_page()

    c.showPage()
    c.save()
    return buf.getvalue()
